"""Builds supabase/functions/settle_fight/sim.js: the game's own battle simulator for the server, cut from docs/index.html.
The functions are copied as written; the tables they read (ships, aliens, defences, weapons, doctrines...) are taken from the running
game (tools/sim_data.js), so every unit added by a later Object.assign is there. Re-run whenever simulate or its tables change:
  THREE_JS=path/to/three.min.js python3 tools/sim_bundle.py
The server and the replay then decide every fight the same way (same inputs + same seed = the same battle)."""
import re, json, subprocess, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FUNCS = ["simulate", "rnd", "cprof", "unitPow", "clamp", "unitCost", "total", "SMALL_R"]   # code (SMALL_R is a Set, so it is copied as code)
FUNCS += [x for x in os.environ.get("SIM_FUNCS", "").split(",") if x]
DATA = ["DOCTRINES", "AL", "CPROF", "CLASS_OF", "SHM", "WPN", "RF", "SH", "DF", "CB_V"]    # plain tables, taken from the running game
DATA += [x for x in os.environ.get("SIM_DATA", "").split(",") if x]
CONSTS = "const ROUND_S = 5, MAX_ROUNDS = 8;"
s = open(os.path.join(ROOT, "docs", "index.html"), encoding="utf-8").read()
main = max(re.finditer(r"<script>(.*?)</script>", s, re.S), key=lambda m: len(m.group(1))).group(1)
assert re.search(r"ROUND_S = 5\b", main) and re.search(r"MAX_ROUNDS = 8\b", main), "ROUND_S / MAX_ROUNDS changed: update CONSTS"
def stmt_end(t, i):
    depth, q, k, esc, fn = 0, None, i, False, t.startswith("function ", i) or t.startswith("async function ", i)
    while k < len(t):
        c = t[k]
        if q:
            if esc: esc = False
            elif c == "\\": esc = True
            elif c == q: q = None
        elif c in "\"'`": q = c
        elif c == "/" and t[k + 1:k + 2] == "/": k = t.find("\n", k); continue
        elif c == "/" and t[k + 1:k + 2] == "*": k = t.find("*/", k) + 2; continue
        elif c in "([{": depth += 1
        elif c in ")]}":
            depth -= 1
            if depth == 0 and c == "}" and fn: return k + 1
        elif c == ";" and depth == 0: return k + 1
        k += 1
    raise ValueError("unterminated statement")
def find(name):
    for pat in [r"(?m)^(?:async )?function %s\(" % name, r"(?m)^\s*(?:const|let) [^;\n]*?\b%s\s*=" % name, r"(?<=[;}{] )function %s\(" % name]:
        m = re.search(pat, main)
        if m:
            i = m.start()
            while main[i] in " \t": i += 1
            return main[i:stmt_end(main, i)]
    raise SystemExit("not found in the game: " + name)
code = [find(n) for n in FUNCS]
env = dict(os.environ); out = subprocess.run(["node", os.path.join(ROOT, "tools", "sim_data.js")] + DATA, capture_output=True, text=True, env=env)
if out.returncode: raise SystemExit("sim_data.js failed: " + out.stderr[-600:])
data = json.loads(out.stdout); missing = [k for k in DATA if data.get(k) is None]; assert not missing, missing
src = ("// GENERATED by tools/sim_bundle.py from docs/index.html (game v%s). Do not edit: re-run the tool.\n" % re.search(r"GAME_V = (\d+)", s).group(1)
       + "const SIMDATA = " + json.dumps(data, separators=(",", ":")) + ";\nconst { " + ", ".join(DATA) + " } = SIMDATA;\n" + CONSTS + "\n"
       + os.environ.get("SIM_PRE", "") + "\n" + "\n".join(code) + "\nexport { " + ", ".join(["simulate", "CB_V"] + [x for x in os.environ.get("SIM_EXPORT", "").split(",") if x]) + " };\n")
dst = os.environ.get("SIM_OUT") or os.path.join(ROOT, "supabase", "functions", "settle_fight", "sim.js"); open(dst, "w").write(src); print("wrote", dst, len(src), "bytes")
